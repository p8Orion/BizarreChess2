    /// <summary>
    /// Marching Cubes mesh extraction from voxel grid.
    /// Based on Paul Bourke's reference implementation.
    /// </summary>
    public static class MarchingCubes
    {
        /// <summary>
        /// Generate mesh from voxel grid using Marching Cubes algorithm.
        /// </summary>
        /// <param name="grid">Voxel grid to process</param>
        /// <param name="isoLevel">Density threshold (0.5 for binary)</param>
        /// <returns>Generated mesh</returns>
        public static Mesh Generate(VoxelGrid grid, float isoLevel = 0.5f)
        {
            var vertices = new List<Vector3>();
            var triangles = new List<int>();
            var vertexCache = new Dictionary<long, int>();

            int res = grid.Resolution;

            // Process each cube in the grid
            for (int x = 0; x < res - 1; x++)
            {
                for (int y = 0; y < res - 1; y++)
                {
                    for (int z = 0; z < res - 1; z++)
                    {
                        ProcessCube(grid, x, y, z, isoLevel, vertices, triangles, vertexCache);
                    }
                }
            }

            var mesh = new Mesh();
            mesh.name = "MarchingCubesMesh";
            
            if (vertices.Count > 65535)
            {
                mesh.indexFormat = UnityEngine.Rendering.IndexFormat.UInt32;
            }
            
            mesh.SetVertices(vertices);
            mesh.SetTriangles(triangles, 0);
            mesh.RecalculateNormals();
            mesh.RecalculateBounds();

            return mesh;
        }

        private static void ProcessCube(
            VoxelGrid grid, int x, int y, int z, float isoLevel,
            List<Vector3> vertices, List<int> triangles,
            Dictionary<long, int> vertexCache)
        {
            // Get density values at 8 corners
            float[] densities = new float[8];
            densities[0] = grid.GetDensity(x, y, z);
            densities[1] = grid.GetDensity(x + 1, y, z);
            densities[2] = grid.GetDensity(x + 1, y, z + 1);
            densities[3] = grid.GetDensity(x, y, z + 1);
            densities[4] = grid.GetDensity(x, y + 1, z);
            densities[5] = grid.GetDensity(x + 1, y + 1, z);
            densities[6] = grid.GetDensity(x + 1, y + 1, z + 1);
            densities[7] = grid.GetDensity(x, y + 1, z + 1);

            // Calculate cube index
            int cubeIndex = 0;
            if (densities[0] >= isoLevel) cubeIndex |= 1;
            if (densities[1] >= isoLevel) cubeIndex |= 2;
            if (densities[2] >= isoLevel) cubeIndex |= 4;
            if (densities[3] >= isoLevel) cubeIndex |= 8;
            if (densities[4] >= isoLevel) cubeIndex |= 16;
            if (densities[5] >= isoLevel) cubeIndex |= 32;
            if (densities[6] >= isoLevel) cubeIndex |= 64;
            if (densities[7] >= isoLevel) cubeIndex |= 128;

            // Cube is entirely inside or outside
            if (EdgeTable[cubeIndex] == 0)
                return;

            // Get corner positions
            Vector3[] corners = new Vector3[8];
            corners[0] = grid.VoxelCornerToWorld(x, y, z);
            corners[1] = grid.VoxelCornerToWorld(x + 1, y, z);
            corners[2] = grid.VoxelCornerToWorld(x + 1, y, z + 1);
            corners[3] = grid.VoxelCornerToWorld(x, y, z + 1);
            corners[4] = grid.VoxelCornerToWorld(x, y + 1, z);
            corners[5] = grid.VoxelCornerToWorld(x + 1, y + 1, z);
            corners[6] = grid.VoxelCornerToWorld(x + 1, y + 1, z + 1);
            corners[7] = grid.VoxelCornerToWorld(x, y + 1, z + 1);

            // Find vertices on edges
            Vector3[] edgeVerts = new Vector3[12];
            
            if ((EdgeTable[cubeIndex] & 1) != 0)
                edgeVerts[0] = Interpolate(corners[0], corners[1], densities[0], densities[1], isoLevel);
            if ((EdgeTable[cubeIndex] & 2) != 0)
                edgeVerts[1] = Interpolate(corners[1], corners[2], densities[1], densities[2], isoLevel);
            if ((EdgeTable[cubeIndex] & 4) != 0)
                edgeVerts[2] = Interpolate(corners[2], corners[3], densities[2], densities[3], isoLevel);
            if ((EdgeTable[cubeIndex] & 8) != 0)
                edgeVerts[3] = Interpolate(corners[3], corners[0], densities[3], densities[0], isoLevel);
            if ((EdgeTable[cubeIndex] & 16) != 0)
                edgeVerts[4] = Interpolate(corners[4], corners[5], densities[4], densities[5], isoLevel);
            if ((EdgeTable[cubeIndex] & 32) != 0)
                edgeVerts[5] = Interpolate(corners[5], corners[6], densities[5], densities[6], isoLevel);
            if ((EdgeTable[cubeIndex] & 64) != 0)
                edgeVerts[6] = Interpolate(corners[6], corners[7], densities[6], densities[7], isoLevel);
            if ((EdgeTable[cubeIndex] & 128) != 0)
                edgeVerts[7] = Interpolate(corners[7], corners[4], densities[7], densities[4], isoLevel);
            if ((EdgeTable[cubeIndex] & 256) != 0)
                edgeVerts[8] = Interpolate(corners[0], corners[4], densities[0], densities[4], isoLevel);
            if ((EdgeTable[cubeIndex] & 512) != 0)
                edgeVerts[9] = Interpolate(corners[1], corners[5], densities[1], densities[5], isoLevel);
            if ((EdgeTable[cubeIndex] & 1024) != 0)
                edgeVerts[10] = Interpolate(corners[2], corners[6], densities[2], densities[6], isoLevel);
            if ((EdgeTable[cubeIndex] & 2048) != 0)
                edgeVerts[11] = Interpolate(corners[3], corners[7], densities[3], densities[7], isoLevel);

            // Create triangles
            for (int i = 0; TriTable[cubeIndex, i] != -1; i += 3)
            {
                int e0 = TriTable[cubeIndex, i];
                int e1 = TriTable[cubeIndex, i + 1];
                int e2 = TriTable[cubeIndex, i + 2];

                int idx0 = GetOrCreateVertex(vertices, vertexCache, edgeVerts[e0], x, y, z, e0);
                int idx1 = GetOrCreateVertex(vertices, vertexCache, edgeVerts[e1], x, y, z, e1);
                int idx2 = GetOrCreateVertex(vertices, vertexCache, edgeVerts[e2], x, y, z, e2);

                triangles.Add(idx0);
                triangles.Add(idx1);
                triangles.Add(idx2);
            }
        }

        private static Vector3 Interpolate(Vector3 p1, Vector3 p2, float v1, float v2, float isoLevel)
        {
            if (Mathf.Abs(v1 - v2) < 0.00001f)
                return (p1 + p2) * 0.5f;

            float t = (isoLevel - v1) / (v2 - v1);
            t = Mathf.Clamp01(t);
            return Vector3.Lerp(p1, p2, t);
        }

        private static int GetOrCreateVertex(
            List<Vector3> vertices, Dictionary<long, int> cache,
            Vector3 pos, int x, int y, int z, int edge)
        {
            // Create unique key for this edge
            long key = ((long)x << 40) | ((long)y << 24) | ((long)z << 8) | (long)edge;
            
            if (cache.TryGetValue(key, out int idx))
                return idx;

            idx = vertices.Count;
            vertices.Add(pos);
            cache[key] = idx;
            return idx;
        }

